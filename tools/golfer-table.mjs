#!/usr/bin/env node
// THE GOLFER TABLE (architect-courses, phase 1, 30 October 2026).
//
//   node tools/golfer-table.mjs          print it
//   node tools/golfer-table.mjs --write  write src/golfer-table.js
//
// The architect places hazards where shots land, so it has to know where they
// land -- for a good player, an average one and a weaker one, with the driver
// and every club after it. Flying shots during generation would cost seconds
// per course (the study, pass 4), so this flies them ONCE, through the game's
// own ball model on a flat fairway, and writes the answer as a small table
// generation reads in microseconds.
//
// What is placed, not measured: the three golfers' driver carries (255, 200 and
// 170 yd) and their spreads. The study's figures are a good player's drive of
// about 250-280 yd in total and an average golfer's 175-225 yd (PLACED and
// commonly cited respectively; RESEARCH.md *Architect courses: the golfer
// table*). Each golfer's other clubs keep the stock bag's gaps, scaled by the
// same factor as the driver. The roll is the ball model's, on default turf.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {generateWorld} from '../src/course.js';
import {simulateShot} from '../src/physics.js';
import {bagClubs, stockBag, CLUBS} from '../src/clubs.js';
import {turfConfig} from '../src/turf.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'golfer-table.js');
const YARD = .9144;

// Driver carry, and the spread of a drive as one standard deviation sideways,
// in yards. PLACED: a scratch golfer about 12 yd, an average one about 20, a
// weaker one about 28 -- a third to a sixth of the carry, wider for the
// weaker player, from nothing more than the commonly quoted landing-zone
// widths of 20-40 yd (the study's sources).
const GOLFERS = {
 good: {driver: 255, side: 12},
 average: {driver: 200, side: 20},
 weak: {driver: 170, side: 28},
};
const KINDS = ['driver', 'wood', 'iron5', 'iron7', 'iron9', 'wedge'];

// A flat, straight fairway long enough for any drive.
const w = generateWorld({seed: 'GOLFER-TABLE', biome: 'heartland', holes: 1, courseYards: 600, elevation: 0, landform: 0,
 doglegs: 0, water: 0, lakes: 0, rivers: 0, creeks: 0, bunkerCount: 0, trees: 0, width: 92, homes: false, fairwayFeature: 0});
const hole = w.holes[0], turf = turfConfig();
const tee = {x: hole.center(30), z: 30};

const table = {};
for (const [name, g] of Object.entries(GOLFERS)) {
 const k = g.driver / CLUBS.driver.carry;
 const yardages = Object.fromEntries(KINDS.map(c => [c, Math.round(CLUBS[c].carry * k)]));
 const clubs = bagClubs(stockBag(yardages));
 const row = {};
 for (const c of KINDS) {
  const club = Object.values(clubs).find(x => x.kind === c);
  if (!club) continue;
  const r = simulateShot({origin: {...tee}, aim: 0, speed: club.speed, vla: club.vla, spin: club.spin, hla: 0, spinAxis: 0}, hole, {turf});
  row[c] = {carry: Math.round(r.carry / YARD), total: Math.round(r.total / YARD)};
 }
 table[name] = {side: g.side, clubs: row};
}

const text = `// GENERATED by tools/golfer-table.mjs -- never edit; re-run it.
// Where three golfers' shots land, flown once through the ball model on a flat
// fairway (architect-courses, phase 1). Yards: carry and total (with roll);
// \`side\` is one standard deviation of a drive sideways (PLACED).
export const GOLFER_TABLE=${JSON.stringify(table)};
`;
for (const [name, g] of Object.entries(table))
 console.log(name.padEnd(8), `side ±${g.side} yd  `, Object.entries(g.clubs).map(([c, v]) => `${c} ${v.carry}/${v.total}`).join('  '));
if (process.argv.includes('--write')) { fs.writeFileSync(OUT, text); console.log(`\nwrote ${path.relative(process.cwd(), OUT)}`); }
