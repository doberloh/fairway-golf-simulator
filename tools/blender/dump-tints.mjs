// EVERY PACK'S FOUR SEASONS, FOR THE GAME (the US landscapes goal, step 9;
// docs/BLENDER_ASSETS.md, *Seasons*).
//
//   node tools/blender/dump-tints.mjs
//
// Each pack script with a `tints(season)` (its LOOK table, from each model's
// spec) is run in Blender with FAIRWAY_DUMP_TINTS set: cartoon.py's export
// then writes the pack's role colours in spring, summer, autumn and winter
// and stops before building anything (seconds a pack). The colours are
// joined to the game's species through the model module's own `family`
// (src/asset-meshes.js; a species draws its family's first model's), and
// written to src/season-tints.js, which vegetation.js reads for a round's
// season. Re-run after a pack's LOOK table changes. Blender only, no
// graphics card work beyond its start (one process at a time all the same).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {MESH_MODELS} from '../../src/asset-meshes.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const DIR = path.join(ROOT, 'tools', 'blender');
function findBlender() {
 if (process.env.BLENDER && fs.existsSync(process.env.BLENDER)) return process.env.BLENDER;
 const base = 'C:/Program Files/Blender Foundation';
 const c = process.platform === 'win32' && fs.existsSync(base) ? fs.readdirSync(base).sort().reverse().map(d => path.join(base, d, 'blender.exe')) : ['/usr/bin/blender', '/Applications/Blender.app/Contents/MacOS/Blender'];
 return c.find(p => fs.existsSync(p)) || 'blender';
}
const packs = fs.readdirSync(DIR).filter(f => /^cartoon_.+\.py$/.test(f) && /^def tints\(/m.test(fs.readFileSync(path.join(DIR, f), 'utf8')));
const byModel = {};
for (const f of packs) {
 const out = path.join(os.tmpdir(), `fairway-tints-${f}.json`);
 fs.rmSync(out, {force: true});
 const run = spawnSync(findBlender(), ['-b', '--factory-startup', '--python', path.join(DIR, f), '--', os.tmpdir()],
  {encoding: 'utf8', maxBuffer: 64 << 20, env: {...process.env, FAIRWAY_DUMP_TINTS: out}});
 if (!fs.existsSync(out)) { console.error(`${f}: no tints written\n${`${run.stdout}\n${run.stderr}`.split(/\r?\n/).slice(-12).join('\n')}`); process.exit(1); }
 const seasons = JSON.parse(fs.readFileSync(out, 'utf8'));
 for (const [season, models] of Object.entries(seasons)) for (const [name, roles] of Object.entries(models)) (byModel[name] ??= {})[season] = roles;
 console.log(`${f}: ${Object.keys(seasons.summer || {}).length} models`);
}
// Species by family: the first model of the family that has tints.
const families = {};
for (const [name, m] of Object.entries(MESH_MODELS)) if (byModel[name] && !families[m.family]) families[m.family] = byModel[name];
// A Meshy pack has no Blender script, so it states its colours itself.
for (const f of fs.readdirSync(path.join(ROOT, 'tools', 'meshy'))) Object.assign(families, JSON.parse(fs.readFileSync(path.join(ROOT, 'tools', 'meshy', f), 'utf8')).seasons || {});
const lines = Object.keys(families).sort().map(k => ` ${k}: ${JSON.stringify(families[k])},`);
fs.writeFileSync(path.join(ROOT, 'src', 'season-tints.js'), `// GENERATED by tools/blender/dump-tints.mjs -- do not edit by hand.
// Each species' role colours (leaf, bark, accent, ...) in each season, from
// its pack's LOOK table (the models' specs); vegetation.js draws a round's
// season with them. A species not listed has no seasons of its own and
// follows the general rules (seasons.js).
export const SEASON_TINTS = {
${lines.join('\n')}
};
`);
console.log(`src/season-tints.js: ${Object.keys(families).length} species`);
